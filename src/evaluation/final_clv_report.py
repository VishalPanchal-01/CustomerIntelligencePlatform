import json
import os
import sys

import pandas as pd

from src.utils.exception import CustomException
from src.utils.logger import logger


class FinalCLVReport:

    def generate_report(
        self,
        metadata: dict,
        feature_importance: pd.DataFrame,
        value_bands: dict,
        output_path: str
    ) -> dict:

        try:

            logger.info(
                "Starting final CLV report generation."
            )

            # ---------------------------------
            # Validate metadata
            # ---------------------------------

            required_metadata_sections = [
                "model",
                "selection",
                "features",
                "target",
                "final_test"
            ]

            missing_sections = [
                section
                for section in required_metadata_sections
                if section not in metadata
            ]

            if missing_sections:

                raise ValueError(
                    f"Missing CLV metadata sections: "
                    f"{missing_sections}"
                )

            # ---------------------------------
            # Validate feature importance
            # ---------------------------------

            if feature_importance.empty:

                raise ValueError(
                    "CLV feature importance is empty."
                )

            required_importance_columns = [
                "Feature",
                "Importance",
                "ImportancePercentage"
            ]

            missing_importance_columns = [
                column
                for column in required_importance_columns
                if column not in feature_importance.columns
            ]

            if missing_importance_columns:

                raise ValueError(
                    f"Missing feature importance columns: "
                    f"{missing_importance_columns}"
                )

            # ---------------------------------
            # Validate value bands
            # ---------------------------------

            required_band_keys = [
                "low_upper_bound",
                "medium_upper_bound"
            ]

            missing_band_keys = [
                key
                for key in required_band_keys
                if key not in value_bands
            ]

            if missing_band_keys:

                raise ValueError(
                    f"Missing CLV value band configuration: "
                    f"{missing_band_keys}"
                )

            # ---------------------------------
            # Feature importance records
            # ---------------------------------

            importance_records = []

            for _, row in feature_importance.iterrows():

                importance_records.append(
                    {
                        "feature":
                            str(
                                row["Feature"]
                            ),

                        "importance":
                            float(
                                row["Importance"]
                            ),

                        "importance_percentage":
                            float(
                                row[
                                    "ImportancePercentage"
                                ]
                            )
                    }
                )

            # ---------------------------------
            # Build final report
            # ---------------------------------

            report = {

                "module": {
                    "name":
                        "Customer Lifetime Value Prediction",

                    "prediction_type":
                        "Regression",

                    "business_output":
                        (
                            "Predicted customer revenue "
                            "for the next 90 days"
                        )
                },

                "target_definition": {

                    "target_name":
                        metadata[
                            "target"
                        ][
                            "name"
                        ],

                    "prediction_horizon_days":
                        int(
                            metadata[
                                "target"
                            ][
                                "prediction_horizon_days"
                            ]
                        ),

                    "definition":
                        (
                            "FutureRevenue is the total valid "
                            "purchase revenue generated by an "
                            "observation-period customer during "
                            "the future prediction window."
                        ),

                    "zero_future_revenue":
                        (
                            "Customers with no valid purchase "
                            "during the prediction window are "
                            "assigned FutureRevenue = 0."
                        ),

                    "modeling_problem":
                        "Regression"
                },

                "features": {
                    "model_features":
                        metadata[
                            "features"
                        ],

                    "customer_id_used_as_feature":
                        False,

                    "date_columns_used_as_features":
                        False
                },

                "methodology": {

                    "temporal_target_design": {
                        "description":
                            (
                                "Customer behavioral features "
                                "are calculated using the "
                                "observation period only, while "
                                "FutureRevenue is calculated from "
                                "the later prediction period."
                            ),

                        "prediction_window_days":
                            int(
                                metadata[
                                    "target"
                                ][
                                    "prediction_horizon_days"
                                ]
                            ),

                        "future_information_used_in_features":
                            False
                    },

                    "target_strategies_compared": [
                        "Raw FutureRevenue",
                        "log1p(FutureRevenue)"
                    ],

                    "candidate_models": [
                        "Dummy Regressor",
                        "Linear Regression",
                        "Random Forest Regressor",
                        "Gradient Boosting Regressor"
                    ],

                    "validation": {
                        "train_test_split":
                            "80/20",

                        "cross_validation":
                            "5-fold KFold on training data",

                        "primary_selection_metric":
                            metadata[
                                "selection"
                            ][
                                "criterion"
                            ],

                        "final_test_used_for_selection":
                            bool(
                                metadata[
                                    "selection"
                                ][
                                    "final_test_used_for_selection"
                                ]
                            )
                    }
                },

                "selected_model": {

                    "algorithm":
                        metadata[
                            "model"
                        ][
                            "name"
                        ],

                    "target_strategy":
                        metadata[
                            "model"
                        ][
                            "target_strategy"
                        ],

                    "best_parameters":
                        metadata[
                            "model"
                        ][
                            "best_parameters"
                        ],

                    "best_cross_validated_mae":
                        float(
                            metadata[
                                "selection"
                            ][
                                "best_cv_mae"
                            ]
                        ),

                    "model_path":
                        metadata[
                            "model"
                        ][
                            "artifact_path"
                        ]
                },

                "final_test_performance": {

                    "customer_count":
                        int(
                            metadata[
                                "final_test"
                            ][
                                "customer_count"
                            ]
                        ),

                    "mae":
                        float(
                            metadata[
                                "final_test"
                            ][
                                "mae"
                            ]
                        ),

                    "rmse":
                        float(
                            metadata[
                                "final_test"
                            ][
                                "rmse"
                            ]
                        ),

                    "r2":
                        float(
                            metadata[
                                "final_test"
                            ][
                                "r2"
                            ]
                        ),

                    "negative_prediction_count":
                        int(
                            metadata[
                                "final_test"
                            ][
                                "negative_prediction_count"
                            ]
                        ),

                    "negative_prediction_percentage":
                        float(
                            metadata[
                                "final_test"
                            ][
                                "negative_prediction_percentage"
                            ]
                        ),

                    "actual_mean":
                        float(
                            metadata[
                                "final_test"
                            ][
                                "actual_mean"
                            ]
                        ),

                    "predicted_mean":
                        float(
                            metadata[
                                "final_test"
                            ][
                                "predicted_mean"
                            ]
                        ),

                    "actual_median":
                        float(
                            metadata[
                                "final_test"
                            ][
                                "actual_median"
                            ]
                        ),

                    "predicted_median":
                        float(
                            metadata[
                                "final_test"
                            ][
                                "predicted_median"
                            ]
                        )
                },

                "feature_importance":
                    importance_records,

                "value_bands": {

                    "method":
                        value_bands.get(
                            "method",
                            "Training target quantiles"
                        ),

                    "low_upper_bound":
                        float(
                            value_bands[
                                "low_upper_bound"
                            ]
                        ),

                    "medium_upper_bound":
                        float(
                            value_bands[
                                "medium_upper_bound"
                            ]
                        ),

                    "definitions":
                        value_bands.get(
                            "definitions",
                            {}
                        )
                },

                "prediction_interface": {

                    "single_customer_prediction":
                        "CLVPredictor.predict()",

                    "batch_prediction":
                        "CLVPredictor.predict_batch()",

                    "prediction_output":
                        [
                            "PredictedFutureRevenue",
                            "CLVValueBand",
                            "PredictionHorizonDays"
                        ],

                    "negative_output_handling":
                        (
                            "Negative predictions are recorded "
                            "for diagnostics and clipped to zero "
                            "for business output."
                        )
                },

                "artifacts":
                    metadata.get(
                        "artifacts",
                        {}
                    )
            }

            # ---------------------------------
            # Create output directory
            # ---------------------------------

            output_directory = os.path.dirname(
                output_path
            )

            if output_directory:

                os.makedirs(
                    output_directory,
                    exist_ok=True
                )

            # ---------------------------------
            # Save JSON
            # ---------------------------------

            with open(
                output_path,
                "w",
                encoding="utf-8"
            ) as file:

                json.dump(
                    report,
                    file,
                    indent=4
                )

            logger.info(
                f"Final CLV report saved to: "
                f"{output_path}"
            )

            return report

        except Exception as e:

            logger.error(
                "Final CLV report generation failed."
            )

            raise CustomException(
                e,
                sys
            )